// Helper functions for compatibility data

export function getCompatibilityPair(slug) {
  return compatibilityPairs[slug.toLowerCase()] || null;
}

export function getAllCompatibilitySlugs() {
  return Object.keys(compatibilityPairs);
}

export function getPairsBySign(signName) {
  return Object.entries(compatibilityPairs)
    .filter(([_, pair]) => 
      pair.sign1.toLowerCase() === signName.toLowerCase() || 
      pair.sign2.toLowerCase() === signName.toLowerCase()
    )
    .map(([slug, pair]) => ({ slug, ...pair }));
}

export function getPairsByElementCombination(element1, element2) {
  return Object.entries(compatibilityPairs)
    .filter(([_, pair]) => 
      (pair.element1.toLowerCase() === element1.toLowerCase() && pair.element2.toLowerCase() === element2.toLowerCase()) ||
      (pair.element1.toLowerCase() === element2.toLowerCase() && pair.element2.toLowerCase() === element1.toLowerCase())
    )
    .map(([slug, pair]) => ({ slug, ...pair }));
}

export function getCompatibilityScore(sign1, sign2) {
  const normalized1 = sign1.toLowerCase();
  const normalized2 = sign2.toLowerCase();
  
  // Try both orderings
  const slug1 = `${normalized1}-and-${normalized2}`;
  const slug2 = `${normalized2}-and-${normalized1}`;
  
  const pair = compatibilityPairs[slug1] || compatibilityPairs[slug2];
  return pair ? pair.score : null;
}

export function getAllSigns() {
  return ['aries', 'taurus', 'gemini', 'cancer', 'leo', 'virgo', 'libra', 'scorpio', 'sagittarius', 'capricorn', 'aquarius', 'pisces'];
}

export function generateAllCompatibilitySlugs() {
  const signs = getAllSigns();
  const slugs = [];
  
  for (let i = 0; i < signs.length; i++) {
    for (let j = i + 1; j < signs.length; j++) {
      slugs.push(`${signs[i]}-and-${signs[j]}`);
    }
  }
  
  return slugs;
}

