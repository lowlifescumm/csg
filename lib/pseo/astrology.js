// Helper functions for programmatic SEO pages

export function getSignBySlug(slug) {
  return zodiacSignsEnriched.find(sign => sign.slug === slug.toLowerCase());
}

export function getSignByName(name) {
  return zodiacSignsEnriched.find(sign => sign.name.toLowerCase() === name.toLowerCase());
}

export function getSignByDate(month, day) {
  return zodiacSignsEnriched.find(sign => {
    const { startDate, endDate } = sign;
    // Handle Capricorn's year-span
    if (sign.name === 'Capricorn') {
      return (month === 12 && day >= startDate.day) || (month === 1 && day <= endDate.day);
    }
    if (startDate.month === endDate.month) {
      return month === startDate.month && day >= startDate.day && day <= endDate.day;
    }
    return (month === startDate.month && day >= startDate.day) ||
           (month === endDate.month && day <= endDate.day);
  });
}

export function getSignsByElement(element) {
  return zodiacSignsEnriched.filter(sign => sign.element.toLowerCase() === element.toLowerCase());
}

export function getSignsByModality(modality) {
  return zodiacSignsEnriched.filter(sign => sign.modality.toLowerCase() === modality.toLowerCase());
}

export function getCompatibleSigns(signName, type = 'best') {
  const sign = getSignByName(signName);
  if (!sign) return [];
  return type === 'best' ? sign.compatibleBest : sign.compatibleWorst;
}

export function getAllSlugs() {
  return zodiacSignsEnriched.map(sign => sign.slug);
}

export function getElementGroups() {
  const elements = ['Fire', 'Earth', 'Air', 'Water'];
  return elements.map(el => ({
    element: el,
    signs: getSignsByElement(el),
    slug: el.toLowerCase(),
    keywords: [el.toLowerCase() + ' signs', el.toLowerCase() + ' zodiac', 'zodiac ' + el.toLowerCase() + ' element'],
    metaDescription: 'Discover the ' + el + ' signs of the zodiac: ' + getSignsByElement(el).map(s => s.name).join(', ') + '. Learn about their shared traits, compatibility, and characteristics.'
  }));
}

export function getModalityGroups() {
  const modalities = ['Cardinal', 'Fixed', 'Mutable'];
  return modalities.map(mod => ({
    modality: mod,
    signs: getSignsByModality(mod),
    slug: mod.toLowerCase(),
    keywords: [mod.toLowerCase() + ' signs', mod.toLowerCase() + ' zodiac', 'zodiac ' + mod.toLowerCase() + ' modality'],
    metaDescription: 'Discover the ' + mod + ' modality signs: ' + getSignsByModality(mod).map(s => s.name).join(', ') + '. Learn how this quality shapes zodiac personality traits.'
  }));
}

